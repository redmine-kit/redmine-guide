# frozen_string_literal: true

# Writes glossary/<lang>.yml: Redmine's interface strings in English and in
# the language, from config/locales of the Redmine release the guide is
# translated for (REDMINE_VERSION, checked against REDMINE_SHA256). Only the
# keys that name things on the screen: labels, fields, buttons, settings,
# permissions, project modules, and the default data's names.
#
#   ruby glossary.rb <lang> <out directory>
require 'net/http'
require 'uri'
require 'zlib'
require 'rubygems/package'
require 'digest'
require 'yaml'
require 'fileutils'

Encoding.default_external = Encoding::UTF_8

LANG = ARGV.fetch(0)
OUT = ARGV.fetch(1)
VERSION = ENV.fetch('REDMINE_VERSION', '7.0.3')
SHA256 = ENV.fetch('REDMINE_SHA256', '0b6b24c033341a9d7ad52cfcfa7b1bc913c191c7a604f740d863f16249dd3c15')
KEYS = /\A(label|field|button|setting|permission|project_module|default|status|enumeration|general_lang)_/

uri = URI("https://www.redmine.org/releases/redmine-#{VERSION}.tar.gz")
tarball = Net::HTTP.get_response(uri)
abort "#{uri}: #{tarball.code}" unless tarball.is_a?(Net::HTTPSuccess)
abort 'checksum mismatch' unless Digest::SHA256.hexdigest(tarball.body) == SHA256

locales = {}
Gem::Package::TarReader.new(Zlib::GzipReader.new(StringIO.new(tarball.body))) do |tar|
  tar.each do |entry|
    name = entry.full_name[%r{config/locales/(en|#{LANG})\.yml\z}, 1]
    locales[name] = YAML.safe_load(entry.read.force_encoding("UTF-8"), aliases: true, permitted_classes: [Symbol]) if name
  end
end
en = locales.fetch('en').fetch('en')
other = locales.fetch(LANG).fetch(LANG)

terms = en.keys.grep(KEYS).sort.filter_map do |key|
  source = en[key]
  target = other[key]
  next unless source.is_a?(String) && target.is_a?(String) && !source.empty?

  { 'key' => key, 'en' => source, LANG => target }
end
FileUtils.mkdir_p(OUT)
header = "# Generated by bin/glossary from Redmine #{VERSION}'s config/locales (en.yml, #{LANG}.yml).\n" \
         "# Do not edit: terms the locale has no string for go in #{LANG}.extra.yml.\n"
File.write(File.join(OUT, "#{LANG}.yml"), header + { 'redmine' => VERSION, 'terms' => terms }.to_yaml.sub(/\A---\n/, ''))
warn "#{terms.size} terms"
